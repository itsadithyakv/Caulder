/**
 * Ember, the little flame: a thirty-two by thirty-two pixel character.
 *
 * Drawn as a sprite rather than as curves, and that is the whole design.
 * A vector mascot at this size is a thing that is approximately a drawing -
 * it needs noise filters and wobble to stop looking plotted, and it never
 * quite arrives. A sprite is not approximating anything. Every pixel is a
 * decision, and animating it means swapping whole frames, which is what
 * animation was before anything could tween.
 *
 * **Why thirty-two and not sixteen or sixty-four.** She is shown at sixty-
 * four pixels, so thirty-two lands on exactly two device pixels per sprite
 * pixel, and integer scaling is the one thing pixel art cannot do without.
 * Sixteen would scale just as cleanly and look bolder, but her wardrobe
 * dies at that size: a pair of glasses is two pixels and reads as a smudge,
 * and there is no room for arms, legs and a book. Sixty-four at sixty-four
 * is one to one, which is not pixel art at all - just a small picture.
 *
 * **She is built in layers**, so one drawing of a body can do everything:
 * a torso that flickers, legs and arms that take up poses, a face, and over
 * the top a costume and whatever she is holding. A move is a list of poses
 * with timings - the moonwalk is eight steps backwards on alternating legs,
 * a spin and a kick - and quarter turns are the only rotation she ever does,
 * because a quarter turn moves every pixel onto another pixel and anything
 * else lands between them.
 *
 * Nothing here is clickable: the button around her is, and a mascot that
 * swallowed the click meant for its own control would be a cute bug.
 */

/** How long a success keeps her pleased before she settles back. */
const PLEASED_MS = 2400;

/** How long a line stays in her speech bubble after she says it. */
const BUBBLE_MS = 1800;

/* ---- The sprites ----------------------------------------------------------
 *
 * Thirty-two rows of thirty-two characters, one per pixel:
 *
 *   `.` nothing   `d` the deep edge   `m` the flame   `p` the hot middle
 *   `k` ink   `w` white   `g` grey   `b` blue
 *   `r` red   `y` gold   `e` green   `n` brown   `a` navy
 *   `h` `j` her right and left hands   `l` her shins   `f` her feet
 *
 * Hands, shins and feet are their own letters because a costume recolours
 * them - white gloves and socks for the moonwalk, red gloves for the ring -
 * and they move with every pose, so they cannot be drawn into the costume.
 *
 * Generated from a script that length-checks every row and renders contact
 * sheets of every costume and move, so a stray pixel is caught on a sheet
 * rather than in the app.
 * -------------------------------------------------------------------------- */

