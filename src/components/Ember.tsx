/* ---- Her outline -----------------------------------------------------------
 *
 * One sprite pixel of ink all the way round her, drawn as pixels rather than
 * computed by a filter. Every layer of her gets an ink twin grown by a pixel
 * each way, drawn beneath all her colours, so what shows is exactly the ring
 * round the outside of whatever she is wearing and holding. The twins carry
 * the same classes as the layers they outline, so they flicker, walk and
 * hide along with them without being told.
 *
 * It was four shadow filters. They looked the same and measured as the most
 * expensive thing about her: a filter re-runs every time anything inside it
 * repaints, and she repaints eight times a second just to burn.
 * ------------------------------------------------------------------------- */

const Inked = createContext(false);
const grown = new WeakMap<Sprite, Sprite>();

/** A sprite grown by one pixel up, down, left and right, all in ink. */
function outlineOf(rows: Sprite): Sprite {
  const known = grown.get(rows);
  if (known) return known;
  const filled = (x: number, y: number) => {
    const ch = rows[y]?.[x];
    return ch !== undefined && ch !== ".";
  };
  const out = rows.map((row, y) =>
    [...row]
      .map((_, x) => (filled(x, y) || filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1) ? "o" : "."))
      .join(""),
  );
  grown.set(rows, out);
  return out;
}

/**
 * One sprite as rects, with runs of the same colour merged into one.
 *
 * A thousand and twenty-four rects a frame, times every layer, times every
 * flame on the screen, is thousands of nodes for a mascot. Merging runs
 * takes each layer to a few dozen, and the drawing is identical: a row of
 * fourteen pixels of one colour IS a rect fourteen wide.
 *
 * Memoised, so a layer that has not changed is not even compared: her
 * torso's three frames and her legs do not move when her face does, and she
 * changes something several times a second.
 */
const Pixels = memo(function Pixels({ rows, className }: { rows: Sprite; className?: string }) {
  const inked = useContext(Inked);
  const rects = useMemo(() => {
    const out: { x: number; y: number; w: number; ink: string; key: string }[] = [];
    (inked ? outlineOf(rows) : rows).forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const ch = row[x] ?? ".";
        const ink = INK[ch];
        if (!ink) {
          x += 1;
          continue;
        }
        let w = 1;
        while (row[x + w] === ch) w += 1;
        out.push({ x, y, w, ink, key: `${x}-${y}` });
        x += w;
      }
    });
    return out;
  }, [rows, inked]);

  return (
    <g className={className}>
      {rects.map((r) => (
        <rect key={r.key} className={r.ink} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </g>
  );
});

/* ---- One pointer, however many flames ------------------------------------
 *
 * Every Ember on the screen wants the same two numbers, and a mousemove
 * listener per component would mean three listeners doing identical work on
 * every pixel of every mouse movement. So there is one listener, attached
 * when the first flame appears and removed when the last one goes.
 */

const pointer = { x: -9999, y: -9999 };
const watchers = new Set<() => void>();
let frame = 0;

function onMove(event: MouseEvent): void {
  pointer.x = event.clientX;
  pointer.y = event.clientY;
  if (frame !== 0) return;
  frame = requestAnimationFrame(() => {
    frame = 0;
    for (const watcher of watchers) watcher();
  });
}

function watchPointer(watcher: () => void): () => void {
  if (watchers.size === 0) window.addEventListener("mousemove", onMove, { passive: true });
  watchers.add(watcher);
  return () => {
    watchers.delete(watcher);
    if (watchers.size === 0) {
      window.removeEventListener("mousemove", onMove);
      if (frame !== 0) cancelAnimationFrame(frame);
      frame = 0;
    }
  };
}

/* ---- One clock, however many flames --------------------------------------
 *
 * Every Ember is the same person, so they must all be reading at the same
 * moment. One interval, shared, rather than one per component, which would
 * drift apart within a minute and turn one mascot into three.
 */

let tick = 0;
const tickers = new Set<(tick: number) => void>();
let clock: ReturnType<typeof setInterval> | undefined;

function watchClock(onTick: (tick: number) => void): () => void {
  if (tickers.size === 0) {
    clock = setInterval(() => {
      tick += 1;
      for (const listener of tickers) listener(tick);
    }, DOING_MS);
  }
  tickers.add(onTick);
  return () => {
    tickers.delete(onTick);
    if (tickers.size === 0) {
      clearInterval(clock);
      clock = undefined;
    }
  };
}

function stillness(): boolean {
  try {
    return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  } catch {
    // A window without matchMedia is a window in a test. Assume motion is fine.
    return false;
  }
}

/**
 * Ember's mood, from what a line is doing.
 *
 * A hook rather than a ternary in each component, because there are two
 * lines and a card wearing the same flame and three copies of the rule would
 * become three different rules. `moodOf` decides; this only supplies it with
 * the hour and turns a success into something that fades - a flame that
 * stays pleased forever is not pleased about anything.
 */
export function useEmberMood({
  busy,
  failed,
  done,
  noticed = false,
}: {
  busy: boolean;
  failed: boolean;
  done: boolean;
  noticed?: boolean;
}): EmberMood {
  const [justDid, setJustDid] = useState(false);
  const [hour, setHour] = useState(() => new Date().getHours());

  useEffect(() => {
    if (!done) return;
    setJustDid(true);
    // A plain timer, not an animation event: under reduced motion there is
    // no animation, so no event would ever fire and she would stay pleased.
    // The same trap the completed-task animation has a suite about.
    const timer = setTimeout(() => setJustDid(false), PLEASED_MS);
    return () => clearTimeout(timer);
  }, [done]);

  // She has to fall asleep while somebody is looking at her, not only when
  // something else happens to redraw the screen. Once a minute is plenty.
  useEffect(() => {
    const beat = setInterval(() => setHour(new Date().getHours()), 60_000);
    return () => clearInterval(beat);
  }, []);

  return moodOf({ busy, failed, justDid, noticed, hour });
}

/**
 * Her speech bubble, placed over her head at the top of the page. Followed
 * frame by frame while it shows, because the line she says while flying
 * across the window should fly with her.
 */
function Say({ text, host }: { text: string; host: RefObject<HTMLSpanElement | null> }) {
  const [at, setAt] = useState<{ x: number; y: number } | null>(null);
  useEffect(() => {
    let frame = 0;
    const place = () => {
      const box = host.current?.getBoundingClientRect();
      if (box && box.width > 0) {
        const x = Math.round(box.left + box.width / 2);
        const y = Math.round(box.top + box.height * 0.06);
        setAt((was) => (was && was.x === x && was.y === y ? was : { x, y }));
      }
      frame = requestAnimationFrame(place);
    };
    place();
    return () => cancelAnimationFrame(frame);
  }, [host]);
  if (!at) return null;
  return createPortal(
    <span className="ember-say" style={{ left: at.x, top: at.y }}>
      {text}
    </span>,
    document.body,
  );
}

